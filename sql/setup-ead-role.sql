-- One role runs the Snowpark job and owns the Streamlit app.
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS EAD_ROLE;
GRANT ROLE EAD_ROLE TO USER DRTOBBE;
GRANT ROLE EAD_ROLE TO ROLE SYSADMIN;
GRANT USAGE, MONITOR ON WAREHOUSE SCALING_BENCH_WH TO ROLE EAD_ROLE;

USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS EAD_LINEAGE;
GRANT USAGE ON DATABASE EAD_LINEAGE TO ROLE EAD_ROLE;
GRANT USAGE, CREATE STREAMLIT ON SCHEMA EAD_LINEAGE.PUBLIC TO ROLE EAD_ROLE;
CREATE TABLE IF NOT EXISTS EAD_LINEAGE.PUBLIC.CTAS_RUNS (
  QUERY_ID VARCHAR(36) NOT NULL,
  RUN_ID VARCHAR NOT NULL,
  STARTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);
GRANT SELECT, INSERT ON TABLE EAD_LINEAGE.PUBLIC.CTAS_RUNS TO ROLE EAD_ROLE;
